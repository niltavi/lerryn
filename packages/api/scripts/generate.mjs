// Generates TypeScript types from an OpenAPI document with openapi-typescript.
//
// Usage: node scripts/generate.mjs [input] [output]
// Paths are relative to the repository root. Defaults generate this
// package's types from the bundled public API spec. The S2 spike reuses the
// script with its own paths so both outputs share one header and one set of
// options.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const [input = "api/bundled/openapi.yaml", output = "packages/api/src/schema.gen.ts"] = process.argv.slice(2);

const generatorPkg = JSON.parse(
  await readFile(path.join(repoRoot, "node_modules/openapi-typescript/package.json"), "utf8"),
);

const ast = await openapiTS(pathToFileURL(path.resolve(repoRoot, input)), {
  // Keep the spec's declaration order so diffs follow edits to the spec.
  alphabetize: false,
  // Exported Schema*/Response*/Parameter* aliases make the types usable
  // without indexing into components["schemas"][...] everywhere.
  rootTypes: true,
  rootTypesNoSchemaPrefix: false,
});

// The header matches the Go convention (^// Code generated .* DO NOT EDIT\.$)
// so tooling treats both sides alike. The generator version is included so
// that an upgrade shows up as a diff in `make generate-check`.
const header =
  `// Code generated by openapi-typescript ${generatorPkg.version} from ${input}. DO NOT EDIT.\n\n`;

const target = path.resolve(repoRoot, output);
await mkdir(path.dirname(target), { recursive: true });
await writeFile(target, header + astToString(ast));
